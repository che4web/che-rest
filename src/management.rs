type ManageResult<T> = Result<T, Box<dyn std::error::Error>>;

const GENERATED_TS_HEADER: &str = "// This file is generated by che-rest. Do not edit manually.\n// Run the appropriate che-rest management generator to update it.\n\n";

#[derive(Debug, Parser)]
#[command(name = "manage")]
#[command(about = "Project management commands for che-rest applications")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    Startapp {
        name: String,

        #[arg(long, default_value = "src/apps")]
        apps_dir: PathBuf,

        #[arg(long = "model")]
        models: Vec<String>,
    },
    Makemigrations {
        app: String,

        #[arg(long, default_value = "src/apps")]
        apps_dir: PathBuf,

        #[arg(long, default_value = "auto")]
        name: String,
    },
    Migrate {
        app: Option<String>,

        #[arg(long, default_value = "src/apps")]
        apps_dir: PathBuf,

        #[arg(long, default_value = "app.toml")]
        config: PathBuf,

        #[arg(long)]
        database_url: Option<String>,
    },
    GenerateTs {
        #[arg(long, default_value = "src/generated")]
        out: PathBuf,
    },
    GenerateAdmin {
        #[arg(long, default_value = "frontend/admin")]
        out: PathBuf,

        #[arg(long)]
        templates_dir: Option<PathBuf>,

        #[arg(long)]
        force: bool,
    },
    GenerateOpenapi {
        #[arg(long, default_value = "openapi.json")]
        out: PathBuf,

        #[arg(long, default_value = "che-rest API")]
        title: String,

        #[arg(long, default_value = "0.1.0")]
        version: String,

        #[arg(long, default_value = "/api")]
        api_prefix: String,
    },
    Createsuperuser {
        #[arg(long, default_value = "app.toml")]
        config: PathBuf,

        #[arg(long)]
        database_url: Option<String>,

        #[arg(long)]
        username: String,

        #[arg(long)]
        password: String,
    },
}

pub struct Management {
    apps: InstalledApps,
}

impl Management {
    pub fn new(apps: InstalledApps) -> Self {
        Self { apps }
    }

    pub async fn run(self) -> ManageResult<()> {
        self.run_from(Cli::parse()).await
    }

    async fn run_from(self, cli: Cli) -> ManageResult<()> {
        match cli.command {
            Command::Startapp {
                name,
                apps_dir,
                models,
            } => startapp(&name, apps_dir, models)?,
            Command::Makemigrations {
                app,
                apps_dir,
                name,
            } => self.makemigrations(&app, apps_dir, &name)?,
            Command::Migrate {
                app,
                apps_dir,
                config,
                database_url,
            } => {
                self.migrate(app.as_deref(), apps_dir, config, database_url)
                    .await?
            }
            Command::GenerateTs { out } => self.generate_ts(out)?,
            Command::GenerateAdmin {
                out,
                templates_dir,
                force,
            } => self.generate_admin(out, templates_dir, force)?,
            Command::GenerateOpenapi {
                out,
                title,
                version,
                api_prefix,
            } => self.generate_openapi(out, title, version, api_prefix)?,
            Command::Createsuperuser {
                config,
                database_url,
                username,
                password,
            } => createsuperuser(config, database_url, &username, &password).await?,
        }

        Ok(())
    }

    fn generate_openapi(
        &self,
        out: PathBuf,
        title: String,
        version: String,
        api_prefix: String,
    ) -> ManageResult<()> {
        let spec = openapi::openapi_json(
            &self.api_endpoints(),
            openapi::OpenApiOptions {
                title,
                version,
                api_prefix,
            },
        );
        if let Some(parent) = out.parent().filter(|parent| !parent.as_os_str().is_empty()) {
            fs::create_dir_all(parent)?;
        }
        fs::write(&out, serde_json::to_string_pretty(&spec)?)?;

        println!("Generated OpenAPI schema in {}", out.display());
        Ok(())
    }

    fn makemigrations(&self, app: &str, apps_dir: PathBuf, name: &str) -> ManageResult<()> {
        validate_app_name(app)?;
        let module = self
            .apps
            .find(app)
            .ok_or_else(|| format!("app is not installed: {app}"))?;

        let migrations_dir = app_migrations_dir(&apps_dir, app);
        fs::create_dir_all(&migrations_dir)?;

        let snapshot_path = migrations_dir.join("schema.json");
        let old_schema = Schema::load_or_empty(&snapshot_path)?;
        let new_schema = app_schema(module);
        let migration = diff_schemas(&old_schema, &new_schema);

        if migration.changes.is_empty() {
            println!("No schema changes detected for app {app}");
            return Ok(());
        }

        let sql = sqlite_migration_sql(&migration);
        let file_name = format!(
            "{:04}_{}.sql",
            next_migration_number(&migrations_dir)?,
            slugify(name)
        );
        let migration_path = migrations_dir.join(file_name);
        fs::write(&migration_path, format!("{sql}\n"))?;
        new_schema.save(snapshot_path)?;

        println!("Created {}", migration_path.display());

        Ok(())
    }

    async fn migrate(
        &self,
        app: Option<&str>,
        apps_dir: PathBuf,
        config: PathBuf,
        database_url: Option<String>,
    ) -> ManageResult<()> {
        let database_url = match database_url {
            Some(database_url) => database_url,
            None => AppConfig::from_file(config)?.database.url,
        };
        let db = SqliteBackend::connect(&database_url).await?;

        match app {
            Some(app) => {
                validate_app_name(app)?;
                if self.apps.find(app).is_none() {
                    return Err(format!("app is not installed: {app}").into());
                }
                apply_app_migrations(&db, &apps_dir, app).await?;
            }
            None => {
                for app in self.apps.names() {
                    apply_app_migrations(&db, &apps_dir, app).await?;
                }
            }
        }

        Ok(())
    }

    fn generate_ts(&self, out: PathBuf) -> ManageResult<()> {
        let endpoints = self.api_endpoints();
        fs::create_dir_all(&out)?;
        fs::write(out.join("api_client.ts"), api_client_ts())?;
        fs::write(out.join("models.ts"), models_ts(&endpoints))?;
        fs::write(out.join("api.ts"), api_ts(&endpoints))?;
        fs::write(out.join("useModelList.ts"), use_model_list_ts())?;
        fs::write(out.join("useModelItem.ts"), use_model_item_ts())?;

        println!("Generated TypeScript API in {}", out.display());
        Ok(())
    }

    fn generate_admin(
        &self,
        out: PathBuf,
        templates_dir: Option<PathBuf>,
        force: bool,
    ) -> ManageResult<()> {
        let api_endpoints = self.api_endpoints();
        let admin_endpoints = self.admin_endpoints();
        let admin_pages = admin_pages(&admin_endpoints);
        fs::create_dir_all(&out)?;

        for template in ADMIN_TEMPLATES {
            write_admin_template(&out, templates_dir.as_deref(), template, force)?;
        }

        for page in &admin_pages {
            write_admin_page(&out, page, AdminPageKind::List, force)?;
            write_admin_page(&out, page, AdminPageKind::Form, force)?;
        }

        write_generated_file(
            &out.join("src/admin/generated/adminSchema.ts"),
            &admin_schema_ts(&admin_endpoints),
        )?;
        write_generated_file(
            &out.join("src/admin/generated/adminRoutes.ts"),
            &admin_routes_ts(&admin_pages),
        )?;
        write_generated_file(
            &out.join("src/admin/adminSchema.ts"),
            &admin_schema_compat_ts(),
        )?;
        write_generated_file(&out.join("src/generated/api_client.ts"), api_client_ts())?;
        write_generated_file(
            &out.join("src/generated/models.ts"),
            &models_ts(&api_endpoints),
        )?;
        write_generated_file(&out.join("src/generated/api.ts"), &api_ts(&api_endpoints))?;
        write_generated_file(
            &out.join("src/generated/useModelList.ts"),
            use_model_list_ts(),
        )?;
        write_generated_file(
            &out.join("src/generated/useModelItem.ts"),
            use_model_item_ts(),
        )?;

        if force {
            println!("Generated Vue admin project in {}", out.display());
        } else {
            println!("Updated generated Vue admin files in {}", out.display());
        }
        Ok(())
    }

    fn api_endpoints(&self) -> Vec<ApiEndpoint> {
        let mut endpoints = Vec::new();
        for module in self.apps.iter() {
            let mut ctx = ModuleContext::new();
            module.init(&mut ctx);
            endpoints.extend(ctx.api_endpoints().iter().cloned());
        }
        endpoints.sort_by(|left, right| left.model_name.cmp(&right.model_name));
        endpoints
    }

    fn admin_endpoints(&self) -> Vec<AdminEndpoint> {
        let mut endpoints = Vec::new();
        for module in self.apps.iter() {
            let mut ctx = ModuleContext::new();
            module.init(&mut ctx);
            endpoints.extend(
                ctx.api_endpoints()
                    .iter()
                    .cloned()
                    .map(|endpoint| AdminEndpoint {
                        app_name: module.name().to_string(),
                        endpoint,
                    }),
            );
        }
        endpoints.sort_by(|left, right| {
            left.app_name
                .cmp(&right.app_name)
                .then_with(|| left.endpoint.model_name.cmp(&right.endpoint.model_name))
        });
        endpoints
    }
}

