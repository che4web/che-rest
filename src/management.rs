fn write_admin_template(
    out: &Path,
    templates_dir: Option<&Path>,
    template: &AdminTemplate,
    force: bool,
) -> ManageResult<()> {
    let target = out.join(template.path);
    if target.exists() && !force {
        return Ok(());
    }

    if let Some(templates_dir) = templates_dir {
        let override_path = templates_dir.join(template.path);
        if override_path.exists() {
            let content = fs::read_to_string(override_path)?;
            return write_generated_file(&target, &content);
        }
    }

    write_generated_file(&target, template.content)
}

fn write_generated_file(path: &Path, content: &str) -> ManageResult<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, content)?;
    Ok(())
}

fn write_admin_page(
    out: &Path,
    page: &AdminPage,
    kind: AdminPageKind,
    force: bool,
) -> ManageResult<()> {
    let (component_name, generic_component) = match kind {
        AdminPageKind::List => (format!("{}List", page.base_name), "GenericModelTable"),
        AdminPageKind::Form => (format!("{}Form", page.base_name), "GenericModelForm"),
    };
    let target = out.join(format!("src/admin/pages/{component_name}.vue"));
    if target.exists() && !force {
        return Ok(());
    }

    let content = format!(
        r#"<script setup lang="ts">
import {{ {model_const} }} from "../generated/adminSchema";
import {generic_component} from "../components/{generic_component}.vue";
</script>

<template>
  <{generic_component} :model="{model_const}" />
</template>
"#,
        model_const = page.model_const,
        generic_component = generic_component,
    );
    write_generated_file(&target, &content)
}

fn admin_pages(endpoints: &[AdminEndpoint]) -> Vec<AdminPage> {
    endpoints
        .iter()
        .map(|admin_endpoint| {
            let base_name = admin_page_base_name(admin_endpoint, endpoints);
            AdminPage {
                app_name: admin_endpoint.app_name.clone(),
                resource: admin_endpoint.endpoint.resource.clone(),
                model_const: format!("{}AdminModel", lower_first(&base_name)),
                base_name,
            }
        })
        .collect()
}

fn admin_page_base_name(admin_endpoint: &AdminEndpoint, endpoints: &[AdminEndpoint]) -> String {
    let model_name = &admin_endpoint.endpoint.model_name;
    let duplicates = endpoints
        .iter()
        .filter(|candidate| candidate.endpoint.model_name == *model_name)
        .count();
    if duplicates > 1 {
        format!("{}{}", camel_case(&admin_endpoint.app_name), model_name)
    } else {
        model_name.clone()
    }
}

async fn createsuperuser(
    config: PathBuf,
    database_url: Option<String>,
    username: &str,
    password: &str,
) -> ManageResult<()> {
    let database_url = match database_url {
        Some(database_url) => database_url,
        None => AppConfig::from_file(config)?.database.url,
    };
    let db = SqliteBackend::connect(&database_url).await?;
    db.create_table::<auth::models::User>().await?;
    db.create_table::<auth::models::AuthToken>().await?;
    db.create_table::<auth::models::AuthSession>().await?;

    let existing = auth::models::User::objects(&db)
        .query()
        .eq("username", username)
        .limit(1)
        .all()
        .await?;
    if !existing.is_empty() {
        return Err(format!("user already exists: {username}").into());
    }

    let password_hash = auth::models::hash_password(password)
        .map_err(|error| format!("failed to hash password: {error}"))?;
    auth::models::User::objects(&db)
        .create()
        .set("username", username)
        .set("password_hash", password_hash)
        .set("is_active", true)
        .set("is_staff", true)
        .set("is_admin", true)
        .set("is_superuser", true)
        .execute()
        .await?;

    println!("Created superuser {username}");
    Ok(())
}

fn app_schema(module: &dyn crate::AppModule) -> Schema {
    let mut ctx = ModuleContext::new();
    module.init(&mut ctx);
    Schema::from_models(ctx.model_schemas().to_vec())
}

fn models_ts(endpoints: &[ApiEndpoint]) -> String {
    let mut out = String::from(GENERATED_TS_HEADER);
    out.push_str("import type { ListParams } from \"./api_client\";\n\n");

    for endpoint in endpoints {
        out.push_str(&format!("export interface {} {{\n", endpoint.model_name));
        for field in endpoint.fields.iter().filter(|field| !field.write_only) {
            out.push_str(&format!("  {}: {};\n", field.name, response_ts_type(field)));
        }
        out.push_str("}\n\n");

        out.push_str(&format!(
            "export interface {}Create {{\n",
            endpoint.model_name
        ));
        for field in endpoint.fields.iter().filter(|field| !field.read_only) {
            out.push_str(&format!(
                "  {}{}: {};\n",
                field.name,
                optional_marker(field),
                ts_type(field.ty, field.nullable)
            ));
        }
        out.push_str("}\n\n");

        out.push_str(&format!(
            "export interface {}Update {{\n",
            endpoint.model_name
        ));
        for field in endpoint.fields.iter().filter(|field| !field.read_only) {
            out.push_str(&format!(
                "  {}?: {};\n",
                field.name,
                ts_type(field.ty, field.nullable)
            ));
        }
        out.push_str("}\n\n");

        out.push_str(&format!(
            "export interface {}ListParams extends ListParams {{\n",
            endpoint.model_name
        ));
        for filter in &endpoint.filters {
            out.push_str(&format!(
                "  {}?: {};\n",
                filter.name,
                ts_type(filter.ty, filter.nullable)
            ));
        }
        out.push_str("}\n\n");
    }

    out
}

fn api_ts(endpoints: &[ApiEndpoint]) -> String {
    let mut out = String::from(GENERATED_TS_HEADER);
    out.push_str("import { createModelApi } from \"./api_client\";\n");

    if endpoints.is_empty() {
        out.push('\n');
        return out;
    }

    out.push_str("import type {\n");
    for endpoint in endpoints {
        out.push_str(&format!("  {},\n", endpoint.model_name));
        out.push_str(&format!("  {}Create,\n", endpoint.model_name));
        out.push_str(&format!("  {}Update,\n", endpoint.model_name));
        out.push_str(&format!("  {}ListParams,\n", endpoint.model_name));
    }
    out.push_str("} from \"./models\";\n\n");

    for endpoint in endpoints {
        out.push_str(&format!(
            "export const {}Api = createModelApi<{}, {}Create, {}Update, {}ListParams>(\"{}\");\n",
            lower_first(&endpoint.model_name),
            endpoint.model_name,
            endpoint.model_name,
            endpoint.model_name,
            endpoint.model_name,
            endpoint.resource
        ));
    }

    out
}

fn optional_marker(field: &ApiField) -> &'static str {
    if field.required && !field.has_default {
        ""
    } else {
        "?"
    }
}

fn ts_type(ty: FieldType, nullable: bool) -> String {
    let base = match ty {
        FieldType::Integer | FieldType::Real => "number",
        FieldType::Text | FieldType::DateTime | FieldType::Choice => "string",
        FieldType::Boolean => "boolean",
        FieldType::Json => "unknown",
    };
    if nullable {
        format!("{base} | null")
    } else {
        base.to_string()
    }
}

fn response_ts_type(field: &ApiField) -> String {
    match &field.related_model {
        Some(model) if field.nullable => format!("{model} | null"),
        Some(model) => model.clone(),
        None => ts_type(field.ty, field.nullable),
    }
}

fn lower_first(value: &str) -> String {
    let mut chars = value.chars();
    match chars.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

fn api_client_ts() -> &'static str {
    r#"// This file is generated by che-rest. Do not edit manually.
// Run the appropriate che-rest management generator to update it.

import axios from "axios";

export interface BaseEntity {
  id?: number;
}

export interface ListParams {
  ordering?: string;
  limit?: number;
  offset?: number;
  [key: string]: string | number | boolean | null | undefined;
}

export interface PaginatedResponse<T> {
  count: number;
  results: T[];
}

export interface ModelApi<
  T extends BaseEntity,
  CreateDTO = Partial<T>,
  UpdateDTO = Partial<T>,
  Params extends ListParams = ListParams,
> {
  list: (params?: Params) => Promise<PaginatedResponse<T>>;
  retrieve: (id: number) => Promise<T>;
  create: (payload: CreateDTO) => Promise<T>;
  update: (id: number, payload: UpdateDTO) => Promise<T>;
  remove: (id: number) => Promise<void>;
}

export const apiClient = axios.create({
  baseURL: import.meta.env.VITE_API_BASE_URL ?? "/api",
  withCredentials: true,
  xsrfCookieName: "che_rest_csrf",
  xsrfHeaderName: "X-CSRF-Token",
  headers: {
    "Content-Type": "application/json",
  },
});

let authToken: string | null = null;

export function setAuthToken(token: string | null) {
  authToken = token;
}

apiClient.interceptors.request.use((config) => {
  if (authToken) {
    config.headers.Authorization = `Token ${authToken}`;
  } else {
    delete config.headers.Authorization;
  }
  return config;
});

export function createModelApi<
  T extends BaseEntity,
  CreateDTO = Partial<T>,
  UpdateDTO = Partial<T>,
  Params extends ListParams = ListParams,
>(resource: string): ModelApi<T, CreateDTO, UpdateDTO, Params> {
  const normalized = resource.endsWith("/") ? resource : `${resource}/`;

  return {
    async list(params) {
      const response = await apiClient.get<PaginatedResponse<T>>(normalized, { params });
      return response.data;
    },

    async retrieve(id) {
      const response = await apiClient.get<T>(`${normalized}${id}/`);
      return response.data;
    },

    async create(payload) {
      const response = await apiClient.post<T>(normalized, payload);
      return response.data;
    },

    async update(id, payload) {
      const response = await apiClient.patch<T>(`${normalized}${id}/`, payload);
      return response.data;
    },

    async remove(id) {
      await apiClient.delete(`${normalized}${id}/`);
    },
  };
}
"#
}

