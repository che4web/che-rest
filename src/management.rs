fn human_label(value: &str) -> String {
    let mut label = String::new();
    for part in value.split('_').filter(|part| !part.is_empty()) {
        if !label.is_empty() {
            label.push(' ');
        }
        let mut chars = part.chars();
        match chars.next() {
            Some(first) => {
                label.push(first.to_ascii_uppercase());
                label.push_str(chars.as_str());
            }
            None => {}
        }
    }
    if label.is_empty() {
        value.to_string()
    } else {
        label
    }
}

