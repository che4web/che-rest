use super::*;

use crate::postgres_test_support as support;

#[test]
fn postgres_schema_sql_and_metadata_discovery_are_offline() {
    let apps = InstalledApps::new().add(crate::auth::module());
    let ddl = schema(&apps).to_sql::<CurrentDialect>();
    assert!(ddl.contains("TIMESTAMPTZ"));
    assert!(!ddl.contains("strftime"));
    let sql = operation_migration_sql(&crate::auth::migrations(), "auth", "0001_initial").unwrap();
    assert!(sql.contains("GENERATED BY DEFAULT AS IDENTITY"));
    assert!(sql.contains("TIMESTAMPTZ"));
    let state = metadata_state().unwrap();
    assert!(!apps.api_endpoints(state).is_empty());
}

#[tokio::test]
#[ignore = "requires TEST_POSTGRES_URL"]
async fn postgres_management_preview_apply_history_verify_and_codegen() {
    support::isolated(|database, url| async move {
        let mut config = AppConfig::default();
        config.database.url = url;
        let migrations = crate::auth::migrations();
        let plan = operation_migration_plan_for_backend(&config, migrations.clone()).await.unwrap();
        assert!(plan.contains("2 pending migration(s)"));
        let listed = operation_migration_list_for_backend(&config, migrations.clone(), None).await.unwrap();
        assert!(listed.contains("[ ] auth:0001_initial"));
        let exists = database.query_sql("SELECT to_regclass('che_migration_history')::text", vec![]).await.unwrap();
        assert!(exists[0].get::<Option<String>>(0).unwrap().is_none());
        assert_eq!(run_operation_migrations(&config,migrations.clone()).await.unwrap(),2);
        assert_eq!(run_operation_migrations(&config,migrations.clone()).await.unwrap(),0);
        verify_operation_migrations(&config,migrations.clone()).await.unwrap();
        let listed = operation_migration_list_for_backend(&config,migrations.clone(),None).await.unwrap();
        assert!(listed.contains("[X] auth:0002_access"));
        let mut changed = migrations;
        changed[0].checksum = "changed".into();
        assert!(operation_migration_plan_for_backend(&config,changed).await.is_err());
        database.execute_sql("ALTER TABLE auth_tokens ADD CONSTRAINT pg_unvalidated FOREIGN KEY(user_id) REFERENCES auth_users(id) NOT VALID",vec![]).await.unwrap();
        assert!(verify_foreign_keys(&config).await.is_err());
        database.execute_sql("ALTER TABLE auth_tokens DROP CONSTRAINT pg_unvalidated",vec![]).await.unwrap();
        let root = std::env::temp_dir().join(format!("che-rest-pg-codegen-{}",che_orm::Uuid::now_v7()));
        fs::create_dir_all(&root).unwrap();
        let config_file = root.join("app.toml");
        // Codegen must not connect, even when the configured URL is unusable.
        fs::write(&config_file,"[database]\nurl='not-a-database-url'\n").unwrap();
        Management::new(InstalledApps::new().add(crate::auth::module()))
            .run_from(Cli { command: CommandKind::GenerateTs { out: root.join("generated"), config: config_file } }).await.unwrap();
        assert!(root.join("generated/models.ts").exists());
        fs::remove_dir_all(root).unwrap();
    }).await;
}
