fn admin_routes(endpoints: &[ApiEndpoint]) -> String {
    let mut out = HEADER.to_owned();
    out.push_str("import type { RouteRecordRaw } from \"vue-router\";\nimport AdminModelList from \"../AdminModelList.vue\";\n");
    for endpoint in endpoints {
        let page = page_name(endpoint, endpoints);
        out.push_str(&format!("import {page}List from \"../pages/{page}List.vue\";\nimport {page}Form from \"../pages/{page}Form.vue\";\n"));
    }
    out.push_str("\nexport const adminRoutes: RouteRecordRaw[] = [\n  { path: \"\", component: AdminModelList },\n");
    for endpoint in endpoints {
        let page = page_name(endpoint, endpoints);
        out.push_str(&format!("  {{ path: {}, component: {page}List }},\n  {{ path: {}, component: {page}Form }},\n  {{ path: {}, component: {page}Form }},\n", js(&endpoint.resource), js(&format!("{}/new", endpoint.resource)), js(&format!("{}/:id/edit", endpoint.resource))));
    }
    out.push_str("];\n");
    out
}

fn admin_type(rust_type: &str, relation: bool) -> &'static str {
    if relation || rust_type.contains("i64") {
        "integer"
    } else if rust_type == "bool" {
        "boolean"
    } else if rust_type.contains("OffsetDateTime") {
        "datetime"
    } else {
        "text"
    }
}
fn last_path_part(value: &str) -> &str {
    value.rsplit("::").next().unwrap_or(value).trim()
}
fn lower_first(value: &str) -> String {
    let mut chars = value.chars();
    chars
        .next()
        .map(|c| c.to_ascii_lowercase())
        .into_iter()
        .chain(chars)
        .collect()
}
fn api_name(endpoint: &ApiEndpoint, endpoints: &[ApiEndpoint]) -> String {
    if endpoints
        .iter()
        .filter(|item| item.model_name == endpoint.model_name)
        .count()
        == 1
    {
        return lower_first(&endpoint.model_name);
    }
    endpoint
        .resource
        .split('/')
        .next_back()
        .unwrap_or(&endpoint.resource)
        .trim_end_matches('s')
        .split('-')
        .enumerate()
        .map(|(index, part)| {
            if index == 0 {
                part.to_owned()
            } else {
                let mut chars = part.chars();
                chars
                    .next()
                    .map(|first| first.to_ascii_uppercase())
                    .into_iter()
                    .chain(chars)
                    .collect()
            }
        })
        .collect()
}
fn page_name(endpoint: &ApiEndpoint, endpoints: &[ApiEndpoint]) -> String {
    let name = if endpoints
        .iter()
        .filter(|item| item.model_name == endpoint.model_name)
        .count()
        == 1
    {
        endpoint.model_name.clone()
    } else {
        endpoint
            .resource
            .split('/')
            .next_back()
            .unwrap_or(&endpoint.resource)
            .trim_end_matches('s')
            .split('-')
            .map(|part| {
                let mut chars = part.chars();
                chars
                    .next()
                    .map(|first| first.to_ascii_uppercase())
                    .into_iter()
                    .chain(chars)
                    .collect::<String>()
            })
            .collect()
    };
    name
}
fn label(value: &str) -> String {
    value
        .replace("__", "_")
        .split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn filter_type(value: &str) -> &'static str {
    if value == "id" || value.ends_with("_id") {
        "integer"
    } else if value.ends_with("_at") {
        "datetime"
    } else {
        "text"
    }
}
fn js(value: &str) -> String {
    serde_json::to_string(value).expect("serializing string cannot fail")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn endpoint(app_name: &'static str, model_name: &str) -> ApiEndpoint {
        ApiEndpoint {
            app_name,
            model_name: model_name.into(),
            resource: model_name.to_ascii_lowercase(),
            fields: Vec::new(),
            columns: Vec::new(),
            filters: Vec::new(),
            extensions: Vec::new(),
        }
    }

    #[test]
    fn groups_multiple_models_under_one_app() {
        let output = admin_schema(&[endpoint("tasks", "Task"), endpoint("tasks", "Note")]);
        assert_eq!(output.matches("name: \"tasks\"").count(), 1);
        assert!(output.contains("taskAdminModel"));
        assert!(output.contains("noteAdminModel"));
    }

    #[test]
    fn creates_static_project_files() {
        let files = static_files(&[endpoint("tasks", "Task")]);
        assert!(files.iter().any(|(path, _)| path == "package.json"));
        assert!(files.iter().any(|(path, _)| path == "tsconfig.json"));
        assert!(
            files
                .iter()
                .any(|(path, _)| path == "src/admin/pages/TaskList.vue")
        );
    }

    #[test]
    fn preserves_static_files_without_force() {
        let root = std::env::temp_dir().join(format!("che_rest_admin_test_{}", std::process::id()));
        let package = root.join("package.json");
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(&package, "custom").unwrap();
        generate(&root, &[endpoint("tasks", "Task")], false).unwrap();
        assert_eq!(std::fs::read_to_string(&package).unwrap(), "custom");
        generate(&root, &[endpoint("tasks", "Task")], true).unwrap();
        assert_ne!(std::fs::read_to_string(&package).unwrap(), "custom");
        let _ = std::fs::remove_dir_all(root);
    }
}
