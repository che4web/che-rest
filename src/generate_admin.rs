use std::{fs, path::Path};

use crate::module::ApiEndpoint;

const HEADER: &str = "// This file is generated by che-rest. Do not edit manually.\n// Run the appropriate che-rest management generator to update it.\n\n";

pub fn generate(
    out: &Path,
    endpoints: &[ApiEndpoint],
    force: bool,
) -> Result<Vec<String>, std::io::Error> {
    let admin_generated = out.join("src/admin/generated");
    let admin_dir = out.join("src/admin");
    fs::create_dir_all(&admin_generated)?;
    fs::create_dir_all(&admin_dir)?;
    let schema_path = admin_generated.join("adminSchema.ts");
    let routes_path = admin_generated.join("adminRoutes.ts");
    fs::write(&schema_path, admin_schema(endpoints))?;
    fs::write(&routes_path, admin_routes(endpoints))?;
    fs::write(
        admin_dir.join("adminSchema.ts"),
        format!("{HEADER}export * from \"./generated/adminSchema\";\n"),
    )?;
    for (relative, contents) in static_files(endpoints) {
        let path = out.join(relative);
        if force || !path.exists() {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(path, contents)?;
        }
    }
    Ok(vec![
        "src/admin/generated/adminSchema.ts".into(),
        "src/admin/generated/adminRoutes.ts".into(),
        "src/admin/adminSchema.ts".into(),
    ])
}

fn admin_schema(endpoints: &[ApiEndpoint]) -> String {
    let mut out = HEADER.to_owned();
    out.push_str("import {\n");
    let mut apps = Vec::new();
    for endpoint in endpoints {
        out.push_str(&format!("  {}Api,\n", api_name(endpoint, endpoints)));
    }
    out.push_str("} from \"../../generated/api\";\n\n");
    out.push_str("export type AdminFieldType = \"integer\" | \"text\" | \"boolean\" | \"real\" | \"datetime\";\n\n");
    out.push_str(
        "export interface AdminField { name: string; source: string; type: AdminFieldType; label: string; readOnly: boolean; writeOnly: boolean; required: boolean; nullable: boolean; hasDefault: boolean; choices?: string[]; relatedModel?: string; relationField?: string; }\n\nexport interface AdminFilter { name: string; source: string; type: AdminFieldType; label: string; nullable: boolean; choices?: string[]; }\n\nexport interface AdminModelApi { list: (params?: any) => Promise<{ count: number; results: any[] }>; retrieve: (id: number) => Promise<any>; create: (payload: any) => Promise<any>; update: (id: number, payload: any) => Promise<any>; remove: (id: number) => Promise<void>; }\n\nexport interface AdminModel { appName: string; name: string; resource: string; api: AdminModelApi; fields: AdminField[]; filters: AdminFilter[]; }\nexport interface AdminApp { name: string; models: AdminModel[]; }\n\nexport const adminModels: AdminModel[] = [\n",
    );
    for endpoint in endpoints {
        out.push_str("  {\n");
        out.push_str(&format!(
            "    appName: {}, name: {}, resource: {}, api: {}Api,\n",
            js(endpoint.app_name),
            js(&endpoint.model_name),
            js(&endpoint.resource),
            api_name(endpoint, endpoints)
        ));
        out.push_str("    fields: [\n");
        for field in &endpoint.fields {
            let related = field.related_model.map(last_path_part);
            let source = field.source.to_owned();
            let ty = admin_type(field.rust_type, related.is_some());
            let nested_relation = related.is_some_and(|_| field.name != field.source);
            let read_only = field.read_only || nested_relation;
            let column = endpoint.columns.iter().find(|column| column.name == source);
            let nullable = column.is_some_and(|column| column.nullable);
            let has_default = column.is_some_and(|column| column.has_default);
            let choices = column
                .and_then(|column| column.choices.as_ref())
                .map(|choices| format!(", choices: {}", serde_json::to_string(choices).unwrap()))
                .unwrap_or_default();
            let related_model = related
                .map(|value| format!(", relatedModel: {}", js(value)))
                .unwrap_or_default();
            let relation_field = if nested_relation {
                format!(", relationField: {}", js(field.name))
            } else {
                String::new()
            };
            out.push_str(&format!("      {{ name: {}, source: {}, type: {}, label: {}, readOnly: {}, writeOnly: {}, required: {}, nullable: {}, hasDefault: {}{}{}{} }},\n", js(field.name), js(&source), js(ty), js(&label(field.name)), read_only, field.write_only, !read_only && !field.write_only && !nullable && !has_default, nullable, has_default, choices, related_model, relation_field));
        }
        out.push_str("    ],\n    filters: [\n");
        for filter in &endpoint.filters {
            let suffix = match filter.lookup {
                crate::Lookup::Exact => "",
                crate::Lookup::Contains => "__contains",
                crate::Lookup::Gt => "__gt",
                crate::Lookup::Gte => "__gte",
                crate::Lookup::Lt => "__lt",
                crate::Lookup::Lte => "__lte",
            };
            let name = format!("{}{}", filter.name, suffix);
            let choices = endpoint
                .columns
                .iter()
                .find(|column| column.name == filter.source)
                .and_then(|column| column.choices.as_ref())
                .map(|choices| format!(", choices: {}", serde_json::to_string(choices).unwrap()))
                .unwrap_or_default();
            out.push_str(&format!(
                "      {{ name: {}, source: {}, type: {}, label: {}, nullable: false{} }},\n",
                js(&name),
                js(filter.source),
                js(filter_type(filter.source)),
                js(&label(&name)),
                choices
            ));
        }
        out.push_str("    ],\n  },\n");
    }
    out.push_str("];\n\n");
    for endpoint in endpoints {
        out.push_str(&format!("export const {}AdminModel = adminModels.find((model) => model.appName === {} && model.resource === {}) as AdminModel;\n", api_name(endpoint, endpoints), js(endpoint.app_name), js(&endpoint.resource)));
    }
    out.push_str("\nexport const adminApps: AdminApp[] = [\n");
    for endpoint in endpoints {
        if apps.contains(&endpoint.app_name) {
            continue;
        }
        apps.push(endpoint.app_name);
        out.push_str(&format!(
            "  {{ name: {}, models: adminModels.filter((model) => model.appName === {}) }},\n",
            js(endpoint.app_name),
            js(endpoint.app_name)
        ));
    }
    out.push_str("];\n");
    out
}

